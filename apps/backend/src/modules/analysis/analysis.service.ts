import { llm } from "@/lib/llm";
import { fromJsonInput, toJsonInput } from "@/lib/json";
import { prisma } from "@/lib/prisma";
import { getFileContent, listFileTree, type FileTreeEntry } from "@/modules/files/files.service";
import { getConnectedRepository } from "@/modules/repositories/repositories.service";
import { withEdgeIds, type GraphEdge } from "@/types/graph";
import {
  architectureAnalysisSchema,
  fileAnalysisSchema,
  type ArchitectureAnalysis,
  type FileAnalysis,
  type FileBlock,
} from "@/modules/analysis/analysis.schema";

const SYSTEM_PROMPT =
  "You are a staff software engineer helping another developer understand an unfamiliar codebase. " +
  "Be concrete and concise. Reference real symbol and file names from the provided input. " +
  "Optimise for skimming: short, punchy sentences over long paragraphs.";

const MAX_FILES_IN_PROMPT = 300;
/** Only the first N lines of a file are sent to the model, to bound cost. */
const MAX_PROMPT_LINES = 800;
const MAX_BLOCKS = 12;
const MAX_HIGHLIGHTS = 6;
const MAX_DEPENDENCIES = 30;

const FILE_BLOCKS_KIND = "file-blocks";
const ARCHITECTURE_KIND = "architecture";

export interface FileAnalysisResult extends FileAnalysis {
  cached: boolean;
}

export interface ArchitectureResult extends ArchitectureAnalysis {
  cached: boolean;
}

export interface NumberedSource {
  text: string;
  truncated: boolean;
}

function splitLines(content: string): string[] {
  const lines = content.replace(/\r\n?/g, "\n").split("\n");

  // A trailing newline is not a real line; drop the empty tail it produces.
  if (lines.length > 1 && lines[lines.length - 1] === "") {
    return lines.slice(0, -1);
  }

  return lines;
}

/** Renders source with `N| ` prefixes so the model can cite exact line numbers. */
export function numberLines(content: string, maxLines: number): NumberedSource {
  const lines = splitLines(content);
  const kept = lines.slice(0, maxLines);

  return {
    text: kept.map((line, index) => `${index + 1}| ${line}`).join("\n"),
    truncated: lines.length > maxLines,
  };
}

function clampLine(value: number, lineCount: number): number {
  if (!Number.isFinite(value)) {
    return 1;
  }

  return Math.min(Math.max(Math.trunc(value), 1), lineCount);
}

/**
 * Turns whatever the model returned into blocks that are safe to render:
 * line ranges clamped to the file, sorted, de-overlapped, de-duplicated by
 * range, and capped in number. Model line numbers are the least reliable part
 * of the output, so this is deliberately forgiving rather than throwing.
 */
export function normalizeBlocks(blocks: FileBlock[], lineCount: number): FileBlock[] {
  if (lineCount < 1) {
    return [];
  }

  const cleaned = blocks
    .map((block) => {
      const a = clampLine(block.startLine, lineCount);
      const b = clampLine(block.endLine, lineCount);

      return {
        name: block.name.trim(),
        kind: block.kind.trim().toLowerCase() || "section",
        startLine: Math.min(a, b),
        endLine: Math.max(a, b),
        label: block.label.trim(),
        detail: block.detail.trim(),
      };
    })
    .filter((block) => block.name.length > 0)
    .sort((a, b) => a.startLine - b.startLine || b.endLine - a.endLine);

  const result: FileBlock[] = [];
  let lastEnd = 0;

  for (const block of cleaned) {
    if (block.startLine <= lastEnd) {
      continue; // overlaps a block we already kept
    }

    const label = block.label || `Lines ${block.startLine}–${block.endLine}`;
    result.push({ ...block, label, detail: block.detail || label });
    lastEnd = block.endLine;

    if (result.length >= MAX_BLOCKS) {
      break;
    }
  }

  return result;
}

function mockFileAnalysis(path: string): FileAnalysis {
  return {
    purpose: `Explains what ${path} does. This text is generated by the mock LLM provider.`,
    highlights: ["Configure a real LLM provider (LLM_PROVIDER=deepseek) to analyse this file."],
    blocks: [],
    dependencies: [],
  };
}

function mockArchitecture(tree: FileTreeEntry[]): ArchitectureAnalysis {
  const groups = new Map<string, number>();

  for (const entry of tree) {
    if (entry.type !== "blob") {
      continue;
    }
    const top = entry.path.split("/")[0] ?? "root";
    groups.set(top, (groups.get(top) ?? 0) + 1);
  }

  const nodes = [
    { id: "app", label: "Application", group: "root" },
    ...[...groups.keys()].map((group) => ({ id: `dir:${group}`, label: group, group: "module" })),
  ];
  const edges: GraphEdge[] = [...groups.keys()].map((group) => ({ source: "app", target: `dir:${group}` }));

  return {
    title: "Application architecture",
    overview: "Modules grouped by their top-level directory (generated by the mock LLM provider).",
    graph: { nodes, edges },
  };
}

export function buildFilePrompt(path: string, source: NumberedSource): string {
  const truncation = source.truncated
    ? `\n\nThe listing is truncated to the first ${MAX_PROMPT_LINES} lines — only reference lines that appear above.`
    : "";

  return [
    `Explain the file "${path}" so a developer who has never seen this repository understands it fast.`,
    "",
    "Return:",
    "- purpose: ONE sentence (max 20 words) describing what the file is for.",
    "- highlights: 3-6 bullets, each max 12 words, covering only what actually matters.",
    "- blocks: the 2-8 MOST IMPORTANT contiguous line ranges (functions, classes, components, hooks, routes, config blocks), each with:",
    "  - name: the symbol or feature name",
    "  - kind: function | class | component | hook | route | config | type | section | feature",
    "  - startLine / endLine: exact line numbers from the numbered listing below (inclusive)",
    "  - label: max 12 words, plain language, what the block does",
    "  - detail: 2-4 sentences explaining how it works, including its inputs and outputs",
    "- dependencies: notable modules or packages this file relies on (names only).",
    "",
    "Prefer fewer, higher-quality blocks over many shallow ones. Skip imports and boilerplate unless they are the point.",
    `Blocks must not overlap and must stay within the file.${truncation}`,
    "",
    'The source is listed below, one row per line, prefixed with "<lineNumber>| ".',
    "",
    "```",
    source.text,
    "```",
  ].join("\n");
}

/**
 * Produces a terse, block-annotated walkthrough of a single file.
 * Cached per file unless `refresh` is set; unknown model output is normalized.
 */
export async function analyzeFile(
  userId: string,
  owner: string,
  name: string,
  path: string,
  options: { refresh: boolean },
): Promise<FileAnalysisResult> {
  const repository = await getConnectedRepository(userId, owner, name);

  if (!options.refresh) {
    const cached = await prisma.analysis.findFirst({
      where: { repositoryId: repository.id, kind: FILE_BLOCKS_KIND, targetPath: path },
      orderBy: { createdAt: "desc" },
    });

    if (cached) {
      return { ...fromJsonInput<FileAnalysis>(cached.content), cached: true };
    }
  }

  const file = await getFileContent(userId, owner, name, path);
  const lineCount = splitLines(file.content).length;
  const source = numberLines(file.content, MAX_PROMPT_LINES);

  const analysis = await llm.generateStructured<FileAnalysis>({
    schema: fileAnalysisSchema,
    schemaName: "FileAnalysis",
    system: SYSTEM_PROMPT,
    prompt: buildFilePrompt(file.path, source),
    mockValue: mockFileAnalysis(file.path),
  });

  const normalized: FileAnalysis = {
    purpose: analysis.purpose.trim(),
    highlights: analysis.highlights
      .map((highlight) => highlight.trim())
      .filter((highlight) => highlight.length > 0)
      .slice(0, MAX_HIGHLIGHTS),
    blocks: normalizeBlocks(analysis.blocks, lineCount),
    dependencies: analysis.dependencies
      .map((dependency) => dependency.trim())
      .filter((dependency) => dependency.length > 0)
      .slice(0, MAX_DEPENDENCIES),
  };

  await prisma.analysis.create({
    data: {
      repositoryId: repository.id,
      kind: FILE_BLOCKS_KIND,
      targetPath: path,
      model: llm.model,
      content: toJsonInput(normalized),
    },
  });

  return { ...normalized, cached: false };
}

/**
 * Produces an architecture map for the repository as a generic node/edge graph.
 */
export async function analyzeArchitecture(
  userId: string,
  owner: string,
  name: string,
  options: { refresh: boolean },
): Promise<ArchitectureResult> {
  const repository = await getConnectedRepository(userId, owner, name);

  if (!options.refresh) {
    const cached = await prisma.analysis.findFirst({
      where: { repositoryId: repository.id, kind: ARCHITECTURE_KIND },
      orderBy: { createdAt: "desc" },
    });

    if (cached) {
      return { ...fromJsonInput<ArchitectureAnalysis>(cached.content), cached: true };
    }
  }

  const tree = await listFileTree(userId, owner, name);
  const fileList = tree
    .filter((entry) => entry.type === "blob")
    .slice(0, MAX_FILES_IN_PROMPT)
    .map((entry) => entry.path)
    .join("\n");

  const analysis = await llm.generateStructured<ArchitectureAnalysis>({
    schema: architectureAnalysisSchema,
    schemaName:
      "ArchitectureAnalysis { title: string, overview: string, graph: { nodes: {id,label,group?}[], edges: {source,target,label?}[] } }",
    system: SYSTEM_PROMPT,
    prompt: `Produce an architecture map for the repository ${owner}/${name}. Group related files into logical modules or layers. Use this file list:\n\n${fileList}`,
    mockValue: mockArchitecture(tree),
  });

  const normalized: ArchitectureAnalysis = { ...analysis, graph: withEdgeIds(analysis.graph) };

  await prisma.analysis.create({
    data: {
      repositoryId: repository.id,
      kind: ARCHITECTURE_KIND,
      model: llm.model,
      content: toJsonInput(normalized),
    },
  });

  return { ...normalized, cached: false };
}
